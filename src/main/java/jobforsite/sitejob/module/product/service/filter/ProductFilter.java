package jobforsite.sitejob.module.product.service.filter;

import jobforsite.sitejob.module.product.dto.ProductFilterDTO;
import jobforsite.sitejob.module.product.model.PostText;
import org.springframework.ui.Model;

import java.util.List;

/**
 * Интерфейс для фильтрации и получения постов продуктов различных категорий.
 * <p>
 * Определяет контракт для сервисов, которые обрабатывают фильтрацию,
 * пагинацию и отображение постов в зависимости от категории продукта.
 * Каждая реализация отвечает за конкретную категорию товаров
 * (например, авто, одежда, электроника и т.д.).
 * </p>
 * <p>
 * Реализации этого интерфейса используются для:
 * <ul>
 *   <li>Получения отфильтрованных постов с пагинацией</li>
 *   <li>Подсчета общего количества постов по фильтрам</li>
 *   <li>Добавления специфичных для категории атрибутов в модель представления</li>
 *   <li>Идентификации категории</li>
 * </ul>
 * </p>
 *
 * @see ProductFilterDTO
 * @see PostText
 */
public interface ProductFilter {

    /**
     * Получает список постов с применением фильтрации и пагинации.
     * <p>
     * Возвращает посты указанной категории, отфильтрованные по параметрам
     * из {@link ProductFilterDTO}, с учетом пагинации (номер страницы и размер).
     * </p>
     *
     * @param filter объект с параметрами фильтрации (поиск, категория, регион, город и др.)
     * @param page   номер страницы (начиная с 0)
     * @param size   количество элементов на странице
     * @return список постов, расширяющих {@link PostText}, либо пустой список,
     *         если посты не найдены
     */
    List<? extends PostText> getPosts(ProductFilterDTO filter, int page, int size);

    /**
     * Подсчитывает общее количество постов, соответствующих фильтрам.
     * <p>
     * Используется для пагинации - позволяет определить общее количество страниц
     * и корректно отображать навигацию.
     * </p>
     *
     * @param filter объект с параметрами фильтрации
     * @return общее количество постов, соответствующих фильтрам
     */
    long getTotalCount(ProductFilterDTO filter);

    /**
     * Добавляет атрибуты в модель представления для отображения в UI.
     * <p>
     * Позволяет каждой категории добавлять свои специфичные атрибуты
     * (например, списки фильтров, опции сортировки, дополнительные параметры)
     * для корректного отображения на странице.
     * </p>
     *
     * @param filter объект с текущими параметрами фильтрации
     * @param model  модель Spring MVC для добавления атрибутов
     */
    void addModelAttributes(ProductFilterDTO filter, Model model);

    /**
     * Возвращает название категории, которую обслуживает данный фильтр.
     * <p>
     * Используется для идентификации и маршрутизации запросов
     * к соответствующему сервису фильтрации.
     * </p>
     *
     * @return строковое название категории (например, "auto", "clothing", "electronics")
     */
    String getCategoryName();

}